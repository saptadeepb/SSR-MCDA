def build_numbers(results: str) -> str:
    d = json.load(open(os.path.join(results, "results.json")))
    out = ["% Auto-generated by make_numbers.py -- DO NOT EDIT BY HAND\n",
           f"% generated {d['generated_utc']}\n\n"]

    out.append(macro("ssrversion", d["package_version"]))
    out.append(macro("mcdraws", f"{d['monte_carlo_draws']:,}".replace(",", "\\,")))
    out.append(macro("epsdefault", f"{d['epsilon']:.2f}"))
    out.append(macro("nposture", len(POST)))
    out.append(macro("ncriteria", len(CRIT)))
    out.append(macro("nsector", len(SECTOR_DEF)))
    out.append(macro("nmoebius", len(CRIT) + len(CRIT) * (len(CRIT) - 1) // 2))
    out.append(macro("nmonotone", f"{len(CRIT) * 2 ** (len(CRIT) - 1):,}".replace(",", "\\,")))
    # number of executable property tests, counted from the test file itself
    tf = os.path.join(os.path.dirname(os.path.abspath(__file__)), "tests", "test_ssr_mcda.py")
    ntests = sum(1 for ln in open(tf) if ln.startswith("def test_"))
    out.append(macro("ntests", ntests))
    out.append("\n")

    for case, c in d["cases"].items():
        T = CASE_TAG[case]
        out.append(f"% ---- case {case} ----\n")
        out.append(macro(f"rec{T}", c["recommended"]))
        out.append(macro(f"rec{T}Desc", esc(POST_DESC[c["recommended"]])))
        out.append(macro(f"norigin{T}", len(c["origins"]) - 1))
        out.append(macro(f"radL{T}", f"{c['stability_radius_l1']:.4f}"))
        out.append(macro(f"radInf{T}", f"{c['stability_radius_linf']:.4f}"))
        out.append(macro(f"radChal{T}", c["stability_challenger"]))
        out.append(macro(f"orness{T}", f"{c['orness']:.3f}"))
        out.append(macro(f"marichalH{T}", f"{c.get('marichal_entropy', float('nan')):.3f}"))
        out.append(macro(f"shannonH{T}", f"{c.get('shapley_entropy', float('nan')):.3f}"))
        out.append(macro(f"minShapley{T}", f"{c.get('min_shapley', 0):g}"))
        # Marichal-Roubens comparator
        mr = c.get("marichal_roubens", {})
        out.append(macro(f"mrSep{T}", f"{mr.get('separation', float('nan')):.4f}"))
        out.append(macro(f"mrDist{T}", f"{mr.get('phi_l1_distance_from_cci', float('nan')):.3f}"))
        out.append(macro(f"mrTau{T}", f"{mr.get('kendall_tau_vs_ssr', float('nan')):.2f}"))
        # preference resampling
        pr = c.get("preference_resampling", {})
        out.append(macro(f"looTau{T}", f"{pr.get('leave_one_out_min_tau', float('nan')):.2f}"))
        surv = pr.get("criteria_exceeding_permutation_null", [])
        out.append(macro(f"nullSurvive{T}",
                         (", ".join(surv) if surv else "none") +
                         (f" ({len(surv)})" if surv else "")))
        out.append(macro(f"nullCount{T}", len(surv)))
        out.append(macro(f"mcPrefViol{T}",
                         c.get("monte_carlo", {}).get("draws_with_preference_violation", 0)))
        out.append(macro(f"cciRounds{T}", c["cci"]["rounds"]))
        out.append(macro(f"cciCuts{T}", c["cci"]["cuts"]))
        out.append(macro(f"cciObj{T}", f"{c['cci']['objective']:.4f}"))
        out.append(macro(f"cciViol{T}", f"{c['cci']['monotonicity_violation']:.1e}"
                                        .replace("e-", r"\times 10^{-").replace("+", "") + "}"))
        out.append(macro(f"bwmXi{T}", f"{c['bwm_consistency_xi']:.4f}"))
        out.append(macro(f"npref{T}", len(c["revealed_preferences"])))
        # is the recommendation zero-regret over the whole admissible capacity set?
        zr = c["max_regret"][c["recommended"]] <= 1e-9
        out.append(macro(f"zeroRegret{T}", "yes" if zr else "no"))
        out.append(macro(f"prefViol{T}", c["cci"].get("preference_violations", 0)))
        out.append(macro(f"mcvalid{T}", f"{c['monte_carlo']['n_valid']:,}".replace(",", "\\,")))
        rr = c["rank_reversal"]
        out.append(macro(f"rrStable{T}", f"{100*rr['recommendation_stable_share']:.0f}"))
        out.append(macro(f"rrOrder{T}", f"{100*rr['choquet_order_preserved_share']:.0f}"))
        out.append(macro(f"rrProbes{T}", rr["probes"]))

        for p in POST:
            a = alpha(p)
            out.append(macro(f"score{T}{a}", f"{c['choquet_scores'][p]:.4f}"))
            out.append(macro(f"regret{T}{a}", f"{c['max_regret'][p]:.4f}"))
            out.append(macro(f"rank{T}{a}", c["mcr_rank"][p]))
            out.append(macro(f"mcone{T}{a}", f"{100*c['monte_carlo']['rank1_frequency'][p]:.1f}"))
            out.append(macro(f"mcmean{T}{a}", f"{c['monte_carlo']['mean_rank'][p]:.2f}"))
            out.append(macro(f"smaa{T}{a}", f"{100*c['smaa_rank1_acceptability'][p]:.1f}"))
        for cr in CRIT:
            a = alpha(cr)
            out.append(macro(f"phi{T}{a}", f"{c['shapley_importance'][cr]:.3f}"))
            out.append(macro(f"phigame{T}{a}", f"{c['shapley_of_game'][cr]:+.3f}"))
        # most and least important criteria
        phis = c["shapley_importance"]
        top = max(phis, key=phis.get)
        bot = min(phis, key=phis.get)
        out.append(macro(f"phiTop{T}", top))
        out.append(macro(f"phiTopName{T}", esc(CRIT_INFO[top][0]).lower()))
        out.append(macro(f"phiTopVal{T}", f"{phis[top]:.3f}"))
        out.append(macro(f"phiBot{T}", bot))
        out.append(macro(f"phiBotName{T}", esc(CRIT_INFO[bot][0]).lower()))
        # agreement with benchmarks
        kt = c["kendall_tau_vs_benchmarks"]
        out.append(macro(f"ktMin{T}", f"{min(kt.values()):.2f}"))
        out.append(macro(f"ktMax{T}", f"{max(kt.values()):.2f}"))
        out.append(macro(f"ktMean{T}", f"{np.mean(list(kt.values())):.2f}"))
        out.append("\n")

    # cross-case
    us, ind = d["cases"]["USA"], d["cases"]["IND"]
    out.append(macro("sameRec", "yes" if us["recommended"] == ind["recommended"] else "no"))
    out.append("\n")
    return "".join(out)


