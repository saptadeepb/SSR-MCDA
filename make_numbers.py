_MATH = re.compile(r"(\$[^$]*\$)")


def _escape_outside_math(text: str) -> str:
    """Escape LaTeX specials in `text` WITHOUT touching anything inside $...$.

    pandas' own `escape=True` escapes indiscriminately, which turns a perfectly good
    `$\\sum_k w_k$` into the literal string `\\$\\textbackslash sum\\_k w\\_k\\$` -- the
    formula then appears in the PDF as source code rather than as mathematics. Since
    several of these tables are mostly mathematics, we escape the prose ourselves and
    hand pandas `escape=False`.
    """
    if not isinstance(text, str):
        return text
    out = []
    for part in _MATH.split(text):
        if part.startswith("$") and part.endswith("$"):
            out.append(part)                      # mathematics: leave exactly as written
        else:
            # Two deliberate omissions. Backslashes are NOT escaped, because the prose
            # in these tables legitimately contains LaTeX accents such as G\"urler and
            # Labb\'e. '~' is NOT escaped either: in these tables it is always a
            # non-breaking space before a cross-reference, never a literal tilde.
            for ch, esc in (("&", r"\&"), ("%", r"\%"), ("#", r"\#"), ("_", r"\_")):
                part = part.replace(ch, esc)
            out.append(part)
    return "".join(out)


def tex_table(df: pd.DataFrame, caption: str, label: str, align: str,
              note: str = "", index: bool = True, float_fmt: str = "%.3f",
              small: bool = True, stretch: float | None = None,
              bottom_pad: str | None = None) -> str:
    """Emit a booktabs-free, \\hline-ruled table.

    ``bottom_pad`` inserts extra vertical space between the final data row and
    the closing rule, e.g. "4pt".  It is needed whenever the last row carries a
    \\displaystyle operator: \\arraystretch scales the nominal row height but a
    double summation descends further than that, and its lower limit would
    otherwise print on top of the rule.
    """
    df = df.copy()
    df = df.map(_escape_outside_math) if hasattr(df, "map") else df.applymap(_escape_outside_math)
    df.columns = [_escape_outside_math(c) for c in df.columns]
    idx_name = None
    if index:
        # The header cell above the row labels must carry the index name, otherwise
        # it reads as if the column headings were shifted one cell to the left.
        # pandas puts a named index on a SECOND header row of empty cells, which
        # wastes a line and looks like a defect, so the name is stripped here and
        # spliced into the first cell of the single header row below.
        idx_name = df.index.name
        df.index = pd.Index([_escape_outside_math(i) for i in df.index], name=None)
        if idx_name:
            idx_name = _escape_outside_math(idx_name)
    body = df.to_latex(index=index, escape=False, float_format=lambda x: float_fmt % x,
                       column_format=align, bold_rows=False)
    body = body.replace("\\toprule", "\\hline").replace("\\midrule", "\\hline") \
               .replace("\\bottomrule", "\\hline")
    if idx_name:
        body = body.replace("\\hline\n & ", "\\hline\n" + idx_name + " & ", 1)
    if bottom_pad:
        # the last "\\\n" before the closing rule is the end of the final data row
        i = body.rfind("\\\\\n\\hline")
        if i >= 0:
            body = body[:i] + f"\\\\[{bottom_pad}]\n\\hline" + body[i + len("\\\\\n\\hline"):]
    sz = "\\small\n" if small else ""
    if stretch:
        sz += f"\\renewcommand{{\\arraystretch}}{{{stretch}}}\n"
    nt = f"\\\\[2pt]\n\\begin{{minipage}}{{\\linewidth}}\\footnotesize {note}\\end{{minipage}}\n" if note else ""
    return (f"\\begin{{table}}[!htbp]\n\\centering\n{sz}"
            f"\\caption{{{caption}}}\n\\label{{{label}}}\n{body}{nt}\\end{{table}}\n")


def build_tables(results: str, out_dir: str) -> None:
    os.makedirs(out_dir, exist_ok=True)
    d = json.load(open(os.path.join(results, "results.json")))

    # T1 criteria definitions
    #
    # Each definition is set in \displaystyle so the summation limits sit above and
    # below the operator rather than beside it; in a table column the default
    # text-style rendering compresses \sum_k \sum_p into an illegible cluster.
    defs = [
        r"\displaystyle\sum_k w_k \sum_p x^{*}_{kp}\, c_{kp}\,(1+\tau_{kp})",
        r"\displaystyle\sum_k w_k \sum_p x^{*}_{kp}\, c_{kp}\,\tau_{kp}",
        r"\displaystyle\sum_k w_k\, x^{*}_{k,\mathrm{DOM}}",
        r"\displaystyle\sum_k w_k \Bigl(1-\sum_p \bigl(x^{*}_{kp}\bigr)^{2}\Bigr)",
        r"\displaystyle\sum_k w_k \sum_p x^{*}_{kp}\, g_p",
        r"\displaystyle\tfrac{1}{5}\sum_k w_k \sum_p x^{*}_{kp}\, \mathrm{LPI}_p",
        # exports are TOTAL bilateral, not sector-specific: E_p, not E_{kp}
        r"\displaystyle\sum_k w_k \Bigl(\sum_p r^{*}_p E_p \Big/ \sum_p E_p\Bigr)",
        r"\displaystyle\sum_k w_k\, \ell_k\, x^{*}_{k,\mathrm{DOM}}",
        r"\displaystyle 10^{-4}\sum_k w_k \sum_p x^{*}_{kp}\, d_p",
    ]
    rows = [{"Code": c, "Criterion": n,
             "Direction": "benefit" if sense == "benefit" else "cost",
             "Definition at the equilibrium": f"${defn}$"}
            for (c, n, sense), defn in zip(S.CRITERIA, defs)]
    t1 = pd.DataFrame(rows)
    open(os.path.join(out_dir, "tab_criteria.tex"), "w").write(
        tex_table(t1, "Evaluation criteria. Every criterion is a functional of the unique "
                      "lower-level response of the Layer-I model, not an independently "
                      "elicited score.",
                  "tab:criteria", "clll",
                  note=r"$w_k$ is the import-value share of sector $k$; $x^{*}$ and $r^{*}$ "
                       r"are the equilibrium sourcing and retaliation vectors; $g_p$ is "
                       r"geopolitical distance and $d_p$ great-circle distance from the focal "
                       r"capital; $\mathrm{LPI}_p$ is the Logistics Performance Index score "
                       r"and $\ell_k$ sector labour intensity. $E_p$ denotes \emph{total} "
                       r"bilateral exports to origin $p$: WITS does not serve export values by "
                       r"product group for these reporters, so C7 measures the share of total "
                       r"exports facing new duties, aggregated with sector weights.",
                  index=False, stretch=1.9, bottom_pad="5pt"))

    # T2 postures
    t2 = pd.DataFrame([{"Code": c, "Posture": desc.split(" (")[0],
                        "Instrument applied to the observed tariff vector": rule}
                       for (c, desc), rule in zip(S.POSTURES, [
                           r"$\tau_p = \tau^{0}_{p}$ for every origin",
                           r"$\tau_p = 0$ for every foreign origin",
                           r"$\tau_p = \tau^{0}_{p} + u$ for every foreign origin",
                           r"$\tau_q = \tau^{0}_{q} + t$ for the dominant rival $q$; "
                           r"$\tau_p = \tau^{0}_{p}$ otherwise",
                           r"$\tau_p = 0$ if $d_p \le \bar{d}$, else $\tau_p = \tau^{0}_{p} + u$",
                           r"$\tau_p = 0$ if $g_p \le \bar{g}$, else $\tau_p = \tau^{0}_{p} + u$",
                           r"$\tau_p = \tau^{0}_{p} + u$, and $c_{\mathrm{DOM}} \mapsto (1-\sigma)\,c_{\mathrm{DOM}}$"])])
    open(os.path.join(out_dir, "tab_postures.tex"), "w").write(
        tex_table(t2, "Tariff-policy postures. Each posture is a rule that maps the observed "
                      "applied-tariff vector into a counterfactual, so no counterfactual tariff "
                      "level is invented.",
                  "tab:postures", "cll",
                  note=r"$u$ is the uniform tariff increment, $t$ the discriminatory increment, "
                       r"$\bar{d}$ the proximity threshold, $\bar{g}$ the alignment threshold and "
                       r"$\sigma$ the domestic cost subsidy; $q$ denotes the origin with the "
                       r"largest observed import share. Every one of these magnitudes is a "
                       r"modelling choice, not an observation, and each is swept over the range "
                       r"given in Table~\ref{tab:params}.",
                  index=False, stretch=1.35))

    # T3 parameters
    # Reference values are carried as STRINGS, not floats, so that each is printed at
    # its own natural precision: a float column formatter would render the margin
    # 0.001 as "0.00" and the threshold 5000 as "5000.000".
    spec = [("$\\rho$", "sourcing convexity (capacity friction)", "0.60", "0.30--1.20"),
            ("$\\lambda$", "weight on geopolitical risk in landed cost", "0.35", "0.10--0.70"),
            ("$\\beta$", "curvature of a partner's welfare cost of retaliating", "1.20", "0.60--2.00"),
            ("$\\gamma$", "fixed escalation cost of retaliating", "0.02", "0.00--0.06"),
            ("$\\theta_0$", "political return to retaliation", "1.00", "0.50--1.50"),
            ("$\\delta_{\\mathrm{DOM}}$", "baseline domestic sourcing share (calibration)", "0.35", "0.15--0.65"),
            ("$\\sigma$", "domestic cost subsidy under $A_7$", "0.15", "0.05--0.30"),
            ("$u$", "uniform tariff increment", "0.10", "0.05--0.20"),
            ("$t$", "discriminatory tariff increment", "0.25", "0.10--0.45"),
            ("$\\bar g$", "alignment threshold for the friendshoring club", "0.80", "0.60--0.95"),
            ("$\\bar{d}$", "proximity threshold, km", "5000", "3000--8000"),
            ("$\\underline{c}$", r"positivity floor pinning the calibration multiplier in~\eqref{eq:calib}", "0.05", "fixed"),
            ("$\\underline{\\varphi}$", r"minimum representativity in~\eqref{eq:cci}", "0.02", "fixed"),
            ("$\\varsigma$", r"representability margin in~\eqref{eq:cci}", "0.001", "fixed"),
            ("$\\varepsilon$", r"capacity uncertainty radius in~\eqref{eq:uncertainty}", "0.05", r"0--0.30, see Fig.~\ref{fig:epsilon}")]
    # the reference value is formatted as TEXT so that a genuinely small parameter
    # such as delta = 0.001 is not rounded to 0.00 by a two-decimal float format
    t3 = pd.DataFrame([{"Symbol": s, "Interpretation": i,
                        "Reference value": v if isinstance(v, str) else f"{v:g}",
                        "Uncertainty range": r} for s, i, v, r in spec])
    open(os.path.join(out_dir, "tab_params.tex"), "w").write(
        tex_table(t3, "Parameters of the framework. The first eleven are behavioural and are swept "
                      "jointly in the Monte-Carlo experiment and singly in the one-at-a-time "
                      "analysis; the next three are numerical devices held fixed; the last, the "
                      "uncertainty radius, is a reporting choice and is swept separately. The "
                      "table lists every non-observed input in one place.",
                  "tab:params", "clrl", index=False, stretch=1.15))

    # T4/T5 performance matrices, T6 capacity, T7 MCR, T8 benchmarks
    digest = json.load(open(os.path.join(results, "results.json")))
    crit_legend = "; ".join(f"{c} {n.lower()}" for c, n, _ in S.CRITERIA)
    post_legend = "; ".join(f"{c} {d.split(' (')[0].lower()}" for c, d in S.POSTURES)

    for case in CASES:
        nm = "the United States" if case == "USA" else "India"
        d_ = digest["cases"][case]

        # ---- normalised performance matrix ----------------------------------
        # The index carries the posture code, so it needs a header of its own;
        # without one the column headings sit one cell to the left of their data.
        Z = pd.read_csv(os.path.join(results, f"performance_norm_{case}.csv")).set_index("posture")
        Z.columns = CRIT
        Z.index = [f"$A_{p[1]}$" for p in Z.index]
        Z.index.name = "Posture"
        open(os.path.join(out_dir, f"tab_perf_{case}.tex"), "w").write(
            tex_table(Z, f"Normalised equilibrium performance matrix $Z$ for {nm}. "
                         f"Values are benefit-oriented, so higher is better on every "
                         f"criterion, and lie in $[0,1]$.",
                      f"tab:perf{case}", "l" + "r" * len(CRIT), float_fmt="%.3f",
                      note="Criteria: " + crit_legend + ". Postures: " + post_legend + "."))

        # ---- identified capacity --------------------------------------------
        cap = pd.read_csv(os.path.join(results, f"capacity_{case}.csv")).set_index("criterion")
        cap = cap[["name", "sense", "shapley_of_game", "shapley_importance", "moebius_singleton"]]
        # The Shapley value of the raw game is the one quantity in the paper that can
        # be negative, and a bare "-0.419" in text mode sets a hyphen, not a minus.
        # Render that column in math mode; the other two are non-negative by
        # construction and are left to the float formatter.
        cap["shapley_of_game"] = [f"${v:.3f}$" for v in cap["shapley_of_game"]]
        cap.columns = ["Criterion", "Direction",
                       r"$\varphi_i(v)$", r"$\varphi_i(\mu^{\star})$", r"$m_i$"]
        cap.index.name = "Code"
        open(os.path.join(out_dir, f"tab_capacity_{case}.tex"), "w").write(
            tex_table(cap, f"Criterion importance for {nm}: the Shapley value of the "
                           f"discrimination game and of the identified 2-additive capacity.",
                      # index + 2 text columns + 3 numeric columns
                      f"tab:cap{case}", "l" + "ll" + "rrr",
                      note=r"$\varphi_i(v)$ is the Shapley value of the raw discrimination "
                           r"game, which need not be a capacity and may therefore be negative; "
                           r"$\varphi_i(\mu^{\star})$ is the importance index of its projection "
                           r"onto the 2-additive capacity polytope, which is non-negative and "
                           r"sums to one; $m_i$ is the corresponding M\"obius singleton "
                           r"coefficient. Section~\ref{sec:resampling} reports how much of this "
                           r"vector a preference sample of this size actually resolves."))

        # ---- Choquet score and minimax regret -------------------------------
        m = pd.read_csv(os.path.join(results, f"mcr_{case}.csv")).set_index("posture")
        m = m[["choquet_score", "score_rank", "max_regret", "mcr_rank", "binding_adversary"]]
        # an alternative with zero regret has no binding adversary; print an en-dash
        # rather than letting pandas render the empty cell as the string "NaN"
        m["binding_adversary"] = [
            f"$A_{str(x)[1]}$" if isinstance(x, str) and x.startswith("A") else "---"
            for x in m["binding_adversary"]
        ]
        has_dash = "---" in list(m["binding_adversary"])
        m.columns = [r"$C_{\mu^{\star}}(z_a)$", "score rank", r"$R(a)$", "MCR rank",
                     "binding adversary"]
        m.index = [f"$A_{p[1]}$" for p in m.index]
        m.index.name = "Posture"
        rec = d_["recommended"]
        rec_regret = d_["max_regret"][rec]
        # the note must state what the numbers actually show: the recommendation is
        # zero-regret for the United States but NOT for India
        if rec_regret <= 1e-9:
            verdict = (f"the recommendation $A_{rec[1]}$ attains zero regret, so by "
                       r"Theorem~\ref{thm:mcr}(iii) it is optimal for \emph{every} "
                       r"admissible capacity")
        else:
            verdict = (f"the recommendation $A_{rec[1]}$ ranks first but carries a strictly "
                       f"positive worst-case regret of ${rec_regret:.4f}$, so it is not optimal "
                       r"for every admissible capacity")
        open(os.path.join(out_dir, f"tab_mcr_{case}.tex"), "w").write(
            tex_table(m, f"Choquet scores and maximum coalitional regret for {nm}.",
                      f"tab:mcr{case}", "l" + "rrrr" + "c",
                      note=(f"Computed at the uncertainty radius "
                            f"$\\varepsilon={digest['epsilon']:.2f}$; the certified stability "
                            f"radius is $\\varepsilon^{{\\star}}_{{\\infty}}="
                            f"{d_['stability_radius_linf']:.4f}$. Here {verdict}."
                            # only explain the dash in the case where one is printed
                            + (" A dash marks an alternative with no binding adversary, "
                               "i.e. one whose regret is attained by no challenger."
                               if has_dash else ""))))

        # ---- comparator ranks -----------------------------------------------
        # TRANSPOSED relative to the natural pivot: with eleven comparators as columns
        # the table is far wider than the text block and the right-hand columns are
        # pushed off the page. Methods therefore become rows and postures columns.
        b = pd.read_csv(os.path.join(results, f"benchmarks_{case}.csv"))
        piv = b.pivot(index="method", columns="posture", values="rank")[POST]
