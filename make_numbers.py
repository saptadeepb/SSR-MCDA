POST = S.POSTURE_CODES
CRIT = S.CRITERION_CODES
POST_DESC = dict(S.POSTURES)
CRIT_INFO = {c: (n, s) for c, n, s in S.CRITERIA}
CASE_TAG = {"USA": "Usa", "IND": "Ind"}
ROMAN = {0: "Zero", 1: "One", 2: "Two", 3: "Three", 4: "Four", 5: "Five",
         6: "Six", 7: "Seven", 8: "Eight", 9: "Nine"}


def esc(s: str) -> str:
    return (s.replace("&", r"\&").replace("%", r"\%").replace("_", r"\_")
             .replace("#", r"\#"))


def macro(name: str, value) -> str:
    return f"\\newcommand{{\\{name}}}{{{value}}}\n"


def alpha(code: str) -> str:
    """A1 -> Aone, C3 -> Cthree, so macro names stay letters-only."""
    return code[0] + ROMAN[int(code[1:])].lower()


